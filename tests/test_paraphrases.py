    def test_typed_clauses_keep_roles_and_comparison_tail(self):
        examples = [
            ('Две пары поставили одновременно', 'Одновременно поставили две пары'),
            ('Лекция в записи слишком длинная', 'В записи лекция слишком длинная'),
            ('Дали две одинаково срочные задачи', 'Две одинаково срочные задачи мне дали'),
            ('Проснулся позже, чем планировал', 'Позже проснулся, чем планировал'),
            ('Друг второй день не отвечает', 'Второй день друг не отвечает'),
            ('Друг второй день не отвечает', 'Друг не отвечает второй день'),
            ('Сегодня почему-то хорошее настроение', 'Почему-то сегодня настроение хорошее'),
            ('Не могу найти ключи, хотя точно принёс их домой', 'Ключи найти не могу, хотя точно домой их принёс'),
        ]
        contrasts = [
            ('Две пары поставили одновременно', 'Две пары поставили по очереди'),
            ('Лекция в записи слишком длинная', 'В записи лекция слишком короткая'),
            ('Дали две одинаково срочные задачи', 'Две одинаково срочные задачи другу дали'),
            ('Проснулся позже, чем планировал', 'Позже планировал, чем проснулся'),
            ('Друг второй день не отвечает', 'Второй день я другу не отвечаю'),
            ('Друг второй день не отвечает', 'Второй день друг отвечает'),
            ('Сегодня почему-то хорошее настроение', 'Почему-то сегодня настроение плохое'),
        ]
        for left, right in examples:
            with self.subTest(left=left, right=right):
                self.assertTrue(equivalent(left, right))
        for left, right in contrasts:
            with self.subTest(left=left, right=right):
                self.assertFalse(equivalent(left, right))

