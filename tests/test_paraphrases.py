    def test_literals_and_unknown_constructions(self):
        for text in ('Переведи «my keys»', 'Он сказал "я сдал экзамен"', "Переведи 'my keys'", '', '  ', 'a\nb', '2+3', 'я' * 1001):
            self.assertIsNone(phrase_features(text), text)
            self.assertFalse(equivalent(text, text))
        self.assertFalse(equivalent('альфа бета гамма', 'гамма бета альфа'))
        self.assertTrue(equivalent('ну альфа бета гамма', 'альфа бета гамма'))

    def test_key_is_hashable_cached_and_keeps_unicode(self):
        question = 'Нұркен пришёл сегодня'
        key = phrase_features(question)
        self.assertIsNotNone(key)
        self.assertEqual({key: 'ok'}[phrase_features(question)], 'ok')
        self.assertIs(key, phrase_features(question))
        self.assertNotEqual(key, phrase_features('Нуркен пришёл сегодня'))


