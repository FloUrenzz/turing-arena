"""Everyday dialogue seeds for the local Russian corpus.

Each vocabulary list supplies one grammatical slot shared by its own situation
patterns. A pattern belongs to a single topic and pairs a complete message with
a relevant reply. These are seeds, before the corpus builder adds phrasings.
"""


def _situations(topic, values, patterns):
    return tuple((topic, prompt.format(value), reply.format(value))
                 for prompt, reply in patterns
                 for value in values.split('|'))


